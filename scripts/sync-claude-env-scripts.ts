/**
 * Copies the customer setup scripts from the claude-env-setup repo and
 * regenerates the embedded copy served at /claude-env.sh and /claude-env.ps1.
 *
 *   bun scripts/sync-claude-env-scripts.ts [path/to/claude-env-setup]
 *
 * Default source: ../claude-env-setup (sibling checkout). Bytes are copied
 * verbatim (the .ps1 keeps its UTF-8 BOM); the test
 * tests/unit/claude-env-scripts.test.ts checks the embedded copy byte-for-byte.
 */
import { createHash } from "node:crypto";
import { copyFile, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const source = resolve(process.argv[2] ?? join(root, "..", "claude-env-setup"));
const target = join(root, "src/features/claude-env/client-scripts");
const names = ["claude-env.sh", "claude-env.ps1"] as const;

const entries: string[] = [];
for (const name of names) {
	await copyFile(join(source, name), join(target, name));
	const bytes = await readFile(join(target, name));
	if (
		name.endsWith(".ps1") &&
		!(bytes[0] === 0xef && bytes[1] === 0xbb && bytes[2] === 0xbf)
	)
		throw new Error(`${name} must start with a UTF-8 BOM`);
	entries.push(
		`\t"${name}": {\n\t\tsha256: "${createHash("sha256").update(bytes).digest("hex")}",\n\t\tbase64:\n\t\t\t"${bytes.toString("base64")}",\n\t},`,
	);
}
await writeFile(
	join(target, "scripts.generated.ts"),
	`// Generated by scripts/sync-claude-env-scripts.ts — do not edit by hand.\nexport const claudeEnvScriptFiles = {\n${entries.join("\n")}\n} as const;\n`,
);
console.log(`synced ${names.join(", ")} from ${source}`);
